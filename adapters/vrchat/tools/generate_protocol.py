#!/usr/bin/env python3
"""Generate the VRChat adapter's Rust and C# protocol bindings."""

import argparse
import json
import re
from pathlib import Path

ADAPTER_ROOT = Path(__file__).resolve().parents[1]
REPOSITORY_ROOT = ADAPTER_ROOT.parents[1]


def outputs():
    manifest = json.loads((ADAPTER_ROOT / "protocol/avatar-parameters.json").read_text())
    if manifest["protocol"] != "xrt-avatar-control" or type(manifest["version"]) is not int:
        raise ValueError("Invalid protocol identity or version")
    parameters = {entry["key"]: entry for entry in manifest["parameters"]}
    if len(manifest["parameters"]) != 3 or set(parameters) != {"enabled", "status", "version"}:
        raise ValueError("Update the protocol consumers before adding parameters")
    for key, kind in (("enabled", "Bool"), ("status", "Int"), ("version", "Int")):
        entry = parameters[key]
        if entry["type"] != kind or entry["saved"] or entry["networkSynced"]:
            raise ValueError(f"Unsupported control parameter contract: {key}")
        expected_default = manifest["version"] if key == "version" else 0
        if entry["default"] != expected_default:
            raise ValueError(f"Unsupported default: {key}")
    expected_statuses = dict(zip(
        ("unavailable", "off", "starting", "active", "stopping", "error"), range(6)
    ))
    if manifest["statuses"] != expected_statuses:
        raise ValueError("Update the control state machine before changing status meanings")
    names = [entry["name"] for entry in parameters.values()]
    if len(set(names)) != len(names) or any(not re.fullmatch(r"XRT/[A-Za-z0-9_]+", name) for name in names):
        raise ValueError("Parameter names must be unique and use the XRT namespace")
    banner = "// Generated by adapters/vrchat/tools/generate_protocol.py; edit adapters/vrchat/protocol/avatar-parameters.json.\n"
    rust = banner + f'pub const PROTOCOL_VERSION: i32 = {manifest["version"]};\n'
    for key, entry in parameters.items():
        rust += f'pub const {key.upper()}_PARAMETER: &str = {json.dumps(entry["name"])};\n'
        rust += f'pub const {key.upper()}_ADDRESS: &str = {json.dumps("/avatar/parameters/" + entry["name"])};\n'
    for name, value in manifest["statuses"].items():
        rust += f"pub const STATUS_{name.upper()}: i32 = {value};\n"
    csharp = banner + "namespace XrtAvatarPlugin.Editor\n{\n    internal static class XrtAvatarProtocol\n    {\n"
    csharp += f'        internal const int Version = {manifest["version"]};\n'
    for key, field in (("enabled", "Enabled"), ("status", "Status"), ("version", "VersionParameter")):
        csharp += f'        internal const string {field} = {json.dumps(parameters[key]["name"])};\n'
    csharp += "    }\n}\n"
    return {
        ADAPTER_ROOT / "control/src/protocol.rs": rust,
        ADAPTER_ROOT / "packages/dev.nowloady.xrt-avatar/Editor/Protocol.g.cs": csharp,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check without writing")
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(REPOSITORY_ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        raise SystemExit("Regenerate protocol bindings: " + ", ".join(stale))


if __name__ == "__main__":
    main()
