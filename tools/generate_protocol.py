#!/usr/bin/env python3
"""Generate the implemented OSC Avatar adapters' Rust and C# bindings."""

import argparse
import json
import re
from pathlib import Path

REPOSITORY_ROOT = Path(__file__).resolve().parents[1]
ADAPTERS = {
    "vrchat": {
        "prefix": "XRT/",
        "namespace": "XrtAvatarPlugin.Editor",
        "class": "XrtAvatarProtocol",
        "csharp": "packages/dev.nowloady.xrt-avatar/Editor/Protocol.g.cs",
    },
    "chilloutvr": {
        "prefix": "#XRT/",
        "namespace": "XrtAvatarPlugin.ChilloutVR.Editor",
        "class": "XrtChilloutProtocol",
        "csharp": "Assets/XRT-Avatar-Plugin/Editor/Protocol.g.cs",
    },
}
PARAMETERS = (("enabled", "Bool"), ("status", "Int"), ("version", "Int"))
STATUSES = dict(zip(("unavailable", "off", "starting", "active", "stopping", "error"), range(6)))


def adapter_outputs(adapter, binding):
    root = REPOSITORY_ROOT / "adapters" / adapter
    manifest_path = root / "protocol/avatar-parameters.json"
    manifest = json.loads(manifest_path.read_text())
    if manifest["protocol"] != "xrt-avatar-control" or type(manifest["version"]) is not int:
        raise ValueError(f"Invalid protocol identity or version: {adapter}")
    if manifest["version"] != 1:
        raise ValueError("Update the connector consumers before changing protocol version")
    parameters = {entry["key"]: entry for entry in manifest["parameters"]}
    if len(manifest["parameters"]) != 3 or set(parameters) != {key for key, _ in PARAMETERS}:
        raise ValueError("Update the protocol consumers before adding parameters")
    for key, kind in PARAMETERS:
        entry = parameters[key]
        if entry["type"] != kind or entry.get("saved", False) or entry["networkSynced"]:
            raise ValueError(f"Unsupported control parameter contract: {adapter}/{key}")
        expected_default = manifest["version"] if key == "version" else 0
        if entry["default"] != expected_default:
            raise ValueError(f"Unsupported default: {adapter}/{key}")
    if "statuses" in manifest and manifest["statuses"] != STATUSES:
        raise ValueError("Update the control state machine before changing status meanings")
    names = [entry["name"] for entry in parameters.values()]
    pattern = re.escape(binding["prefix"]) + r"[A-Za-z0-9_]+"
    if len(set(names)) != len(names) or any(not re.fullmatch(pattern, name) for name in names):
        raise ValueError(f"Parameter names must be unique and use {binding['prefix']}")
    banner = ("// Generated by tools/generate_protocol.py; edit "
              + manifest_path.relative_to(REPOSITORY_ROOT).as_posix() + ".\n")
    rust = banner + f'pub const PROTOCOL_VERSION: i32 = {manifest["version"]};\n'
    for key, _ in PARAMETERS:
        name = parameters[key]["name"]
        rust += f'pub const {key.upper()}_PARAMETER: &str = {json.dumps(name)};\n'
        rust += f'pub const {key.upper()}_ADDRESS: &str = {json.dumps("/avatar/parameters/" + name)};\n'
    for name, value in manifest.get("statuses", {}).items():
        rust += f"pub const STATUS_{name.upper()}: i32 = {value};\n"
    csharp = banner + "namespace " + binding["namespace"] + "\n{\n    internal static class " + binding["class"] + "\n    {\n"
    csharp += f'        internal const int Version = {manifest["version"]};\n'
    for key, field in (("enabled", "Enabled"), ("status", "Status"), ("version", "VersionParameter")):
        csharp += f'        internal const string {field} = {json.dumps(parameters[key]["name"])};\n'
    csharp += "    }\n}\n"
    return {
        root / "control/src/protocol.rs": rust,
        root / binding["csharp"]: csharp,
    }


def caption_outputs(adapter, binding):
    root = REPOSITORY_ROOT / "adapters" / adapter
    source = root / "protocol/caption.json"
    manifest = json.loads(source.read_text())
    if (manifest["protocol"] != "xrt-avatar-caption" or manifest["version"] != 1
            or manifest["slots"] != 128 or manifest["encoding"] != "unicode-bmp-big-endian"
            or manifest["pointerUnit"] != "chunk" or manifest["clearPointer"] != 255):
        raise ValueError("Update caption consumers before changing the wire contract")
    profiles = manifest["profiles"]
    bus_counts = [p["bytesPerChunk"] for p in profiles]
    expected = [8, 4, 2] if adapter == "vrchat" else [8]
    if bus_counts != expected or any(p["glyphsPerChunk"] * 2 != p["bytesPerChunk"] for p in profiles):
        raise ValueError("Invalid caption bus profiles")
    if adapter == "vrchat" and any(p["syncBits"] != (p["bytesPerChunk"] + 1) * 8 for p in profiles):
        raise ValueError("Invalid VRChat synchronization cost")
    if adapter == "chilloutvr" and (
            manifest["bus"]["wordCount"] != 2 or
            manifest["bus"]["packing"] != "two-bmp-codepoints-per-signed-int32-high-first" or
            any(p["syncedParameters"] != 3 or p["syncBits"] != 96 for p in profiles)):
        raise ValueError("Invalid ChilloutVR word bus")
    fields = {
        "VersionParameter": manifest["capabilities"]["version"],
        "ColumnsParameter": manifest["capabilities"]["columns"],
        "BytesParameter": manifest["capabilities"]["bytesPerChunk"],
        "Pointer": manifest["bus"]["pointer"],
    }
    data_field = "BytePrefix" if adapter == "vrchat" else "WordPrefix"
    fields[data_field] = manifest["bus"]["bytePrefix" if adapter == "vrchat" else "wordPrefix"]
    prefix = fields["Pointer"].removesuffix("Pointer")
    capability_prefix = binding["prefix"] + "Caption/"
    expected_fields = {
        "VersionParameter": capability_prefix + "Version",
        "ColumnsParameter": capability_prefix + "Columns",
        "BytesParameter": capability_prefix + "Bytes",
        "Pointer": "XRT/Caption/Pointer",
        data_field: "XRT/Caption/" + ("Byte" if adapter == "vrchat" else "Word"),
    }
    if fields != expected_fields:
        raise ValueError("Invalid caption parameter names")
    class_name = "XrtCaptionProtocol" if adapter == "vrchat" else "XrtChilloutCaptionProtocol"
    result = ("// Generated by tools/generate_protocol.py; edit " + source.relative_to(REPOSITORY_ROOT).as_posix() + ".\n"
              "namespace " + binding["namespace"] + "\n{\n    internal static class " + class_name + "\n    {\n")
    result += f'        internal const string Prefix = {json.dumps(prefix)};\n'
    for name, value in fields.items():
        result += f'        internal const string {name} = {json.dumps(value)};\n'
    for name, value in (("Version", manifest["version"]), ("Slots", manifest["slots"]),
                        ("ClearPointer", manifest["clearPointer"]),
                        ("HorizontalColumns", manifest["presets"]["horizontal"]["columns"]),
                        ("PortraitColumns", manifest["presets"]["portrait"]["columns"])):
        result += f'        internal const int {name} = {value};\n'
    if adapter == "chilloutvr":
        result += f'        internal const int BusWordCount = {manifest["bus"]["wordCount"]};\n'
    result += "        internal static readonly int[] BusByteCounts = { " + ", ".join(map(str, bus_counts)) + " };\n    }\n}\n"
    target = Path(binding["csharp"]).parent / "Caption/Protocol.g.cs"
    return {root / target: result}


def outputs():
    result = {path: content for adapter, binding in ADAPTERS.items()
              for path, content in adapter_outputs(adapter, binding).items()}
    for adapter, binding in ADAPTERS.items():
        result.update(caption_outputs(adapter, binding))
    result.update(catalog_outputs())
    return result


def catalog_outputs():
    """The host consumes these descriptors instead of repeating platform rules."""
    catalog = json.loads((REPOSITORY_ROOT / "connectors/catalog.json").read_text())
    entries = catalog["connectors"]
    ids = [entry["id"] for entry in entries]
    if (len(set(ids)) != len(ids) or catalog["default"] not in ids
            or any(not re.fullmatch(r"[a-z][a-z0-9]*", name) for name in ids)):
        raise ValueError("Invalid connector catalog")
    result = "// Generated by tools/generate_protocol.py from connectors/catalog.json and adapter manifests.\n"
    result += "use crate::osc;\nuse serde::{Deserialize, Serialize};\n\n"
    result += '#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]\n#[serde(rename_all = "snake_case")]\npub enum Connector {\n'
    for entry in entries:
        if entry["id"] == catalog["default"]:
            result += "    #[default]\n"
        result += f'    {entry["id"].capitalize()},\n'
    result += "}\n\nimpl Connector {\n"
    result += f'    pub const ALL: [Self; {len(entries)}] = [\n'
    result += "".join("        Self::" + name.capitalize() + ",\n" for name in ids) + "    ];\n"
    for method, field in (("id", "id"), ("label", "label")):
        result += f"    pub const fn {method}(self) -> &'static str {{\n        match self {{\n"
        for entry in entries:
            result += f'            Self::{entry["id"].capitalize()} => {json.dumps(entry[field])},\n'
        result += "        }\n    }\n"
    result += "    pub fn osc(self) -> Option<&'static osc::Contract> {\n        match self {\n"
    osc_entries = [entry for entry in entries if entry["transport"] == "oscquery"]
    if any(entry["transport"] not in ("oscquery", "websocket") for entry in entries):
        raise ValueError("Unsupported connector transport")
    for entry in osc_entries:
        result += f'            Self::{entry["id"].capitalize()} => Some(&{entry["id"].upper()}),\n'
    result += "            _ => None,\n        }\n    }\n}\n\n"
    address = lambda name: json.dumps("/avatar/parameters/" + name)
    for entry in osc_entries:
        root = REPOSITORY_ROOT / "adapters" / entry["id"] / "protocol"
        control = json.loads((root / "avatar-parameters.json").read_text())
        caption = json.loads((root / "caption.json").read_text())
        parameters = {p["key"]: p["name"] for p in control["parameters"]}
        bus = caption["bus"]
        width = bus["integerBytes"]
        counts = [p["bytesPerChunk"] for p in caption["profiles"]]
        if (width not in (1, 4) or any(count <= 0 or count % max(width, 2) for count in counts)
                or any(count not in (8, 16, 32) for count in caption["columnCounts"])
                or control["identityPath"] not in control["invalidatePaths"]):
            raise ValueError("Invalid OSC descriptor")
        data_prefix = bus["bytePrefix" if width == 1 else "wordPrefix"]
        result += f'const {entry["id"].upper()}: osc::Contract = osc::Contract {{\n    peer: osc::Peer {{\n'
        for field, key in (("service_name", "serviceName"), ("identity_path", "identityPath")):
            result += f'        {field}: {json.dumps(control[key])},\n'
        result += f'        invalidate_paths: &{json.dumps(control["invalidatePaths"])},\n'
        mute = "Some(" + json.dumps(control["mutePath"]) + ")" if control["mutePath"] else "None"
        result += f'        mute_path: {mute},\n    }},\n'
        for field in ("enabled", "status", "version"):
            result += f'    {field}: {address(parameters[field])},\n'
        result += f'    protocol_version: {control["version"]},\n    caption: osc::CaptionContract {{\n'
        for field, key in (("version", "version"), ("columns", "columns"), ("bytes", "bytesPerChunk")):
            result += f'        {field}: {address(caption["capabilities"][key])},\n'
        result += f'        pointer: {address(bus["pointer"])},\n        data_prefix: {address(data_prefix)},\n'
        for field, value in (("protocol_version", caption["version"]), ("slots", caption["slots"]),
                             ("clear_pointer", caption["clearPointer"]), ("integer_bytes", width),
                             ("interval_ms", caption["delivery"]["defaultChunkIntervalMs"])):
            result += f'        {field}: {value},\n'
        result += f'        column_counts: &{json.dumps(caption["columnCounts"])},\n'
        result += f'        bytes_per_chunk: &{json.dumps(counts)},\n'
        idle = caption["delivery"].get("receiverIdleTimeoutMs")
        result += f'        receiver_idle_ms: {"Some(" + str(idle) + ")" if idle else "None"},\n    }},\n}};\n\n'
    if catalog["default"] not in [entry["id"] for entry in osc_entries]:
        raise ValueError("The default OSC peer must have an OSC contract")
    result += f'pub(crate) const DEFAULT_PEER: osc::Peer = {catalog["default"].upper()}.peer;\n'
    return {REPOSITORY_ROOT / "crates/connector-core/src/catalog.rs": result}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check without writing")
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(REPOSITORY_ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        raise SystemExit("Regenerate protocol bindings: " + ", ".join(stale))


if __name__ == "__main__":
    main()
