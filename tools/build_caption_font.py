#!/usr/bin/env python3
"""Build the shared Noto caption SDF and Unicode lookup (Pillow, NumPy, SciPy, fontTools).

Input: Noto Sans CJK SC Regular 2.004 from the pinned upstream source in the
manifest. Original font downloads stay outside the package. Use --preview for a
CPU-rendered proof that samples the same distance-field pixels as the shader.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "presentation/unity/Runtime/Caption"
SOURCE_SHA256 = "2c76254f6fc379fddfce0a7e84fb5385bb135d3e399294f6eeb6680d0365b74b"
SOURCE = "https://raw.githubusercontent.com/notofonts/noto-cjk/f8d157532fbfaeda587e826d4cd5b21a49186f7c/Sans/OTF/SimplifiedChinese/NotoSansCJKsc-Regular.otf"
CELL, GRID, SCALE, SPREAD = 32, 128, 4, 4


def repertoire():
    points = set(range(0x20, 0x530)) | {0xFFFD}
    # These standards provide useful CJK coverage without shipping every Unicode
    # ideograph. The generated manifest records the exact supported code points.
    for encoding in ("gb2312", "shift_jis", "euc_kr"):
        for first in range(256):
            for second in range(256):
                try:
                    text = bytes((first, second)).decode(encoding)
                    if len(text) == 1:
                        points.add(ord(text))
                except UnicodeDecodeError:
                    pass
    return points


def build_bindings(output: Path):
    """Keep fixed Animator property names outside the hand-written rendering code."""
    def select(first, end, indent="    "):
        if end - first == 1:
            return f"{indent}return float2(_Byte{first * 2}, _Byte{first * 2 + 1});"
        middle = (first + end) // 2
        return (f"{indent}[branch] if (index < {middle})\n{indent}{{\n"
                + select(first, middle, indent + "    ") + f"\n{indent}}}\n{indent}else\n{indent}{{\n"
                + select(middle, end, indent + "    ") + f"\n{indent}}}")
    lines = ["// Generated by tools/build_caption_font.py --bindings.\n", "#ifndef XRT_CAPTION_BYTES_INCLUDED", "#define XRT_CAPTION_BYTES_INCLUDED", ""]
    for start in range(0, 256, 8):
        lines.append("float " + ", ".join(f"_Byte{i}" for i in range(start, start + 8)) + ";")
    lines += ["", "float2 XrtReadCell(int index)", "{", select(0, 128), "}", "", "float XrtByteTotal()", "{"]
    lines.append("    return " + " +\n           ".join(" + ".join(f"_Byte{i}" for i in range(start, start + 8)) for start in range(0, 256, 8)) + ";")
    lines += ["}", "", "#endif", ""]
    output.mkdir(parents=True, exist_ok=True)
    (output / "XrtCaptionBytes.hlsl").write_text("\n".join(lines))
    shader = output / "XrtAvatarCaption.shader"
    if shader.exists():
        source = shader.read_text()
        begin, end = "        // bytes:start", "        // bytes:end"
        before, remainder = source.split(begin, 1)
        _, after = remainder.split(end, 1)
        properties = "\n".join(f'        [HideInInspector] _Byte{i} ("Byte {i}", Float) = 0' for i in range(256))
        shader.write_text(before + begin + "\n" + properties + "\n" + end + after)


def render_preview(output: Path, destination: Path):
    import numpy as np
    from PIL import Image, ImageDraw
    manifest = json.loads((output / "XrtCaptionFont.json").read_text())
    atlas = Image.open(output / "XrtCaptionSdf.png")
    lookup = Image.open(output / "XrtCaptionMap.png")
    mapping = manifest["codepoints"]
    lines = ["The entrance is on the right.", "入口在右边，我们在楼梯旁等你。", "入口は右です。階段のそばで待ちます。", "Привет! Рады вас видеть.", "안녕하세요! 만나서 반가워요."]
    image = Image.new("RGB", (1540, 570), "#edf0f2")
    draw = ImageDraw.Draw(image)
    draw.rounded_rectangle((32, 28, 1508, 542), radius=26, fill="#fafbfc")
    size = 44
    for row, line in enumerate(lines):
        offset = 0.0
        for char in line:
            index = mapping.get(f"{ord(char):04X}", 1)
            x, y = index % GRID * CELL, index // GRID * CELL
            sdf = atlas.crop((x, y, x + CELL, y + CELL)).resize((size, size), Image.Resampling.BILINEAR)
            distance = (np.asarray(sdf, dtype=np.float32) / 255 - .5) * (2 * SPREAD) * size / CELL
            coverage = np.clip(distance + .5, 0, 1)
            mask = Image.fromarray((coverage * 255).astype("uint8"))
            advance = lookup.getpixel((ord(char) & 255, ord(char) >> 8))[2] / 255
            image.paste("#35424d", (round(58 + (offset + advance * .5 - .5) * size), 64 + row * 92), mask)
            offset += advance
    destination.parent.mkdir(parents=True, exist_ok=True)
    image.save(destination)


def build(font_path: Path, output: Path):
    import numpy as np
    from fontTools.ttLib import TTFont
    from PIL import Image, ImageDraw, ImageFont
    from scipy.ndimage import distance_transform_edt
    source_bytes = font_path.read_bytes()
    if hashlib.sha256(source_bytes).hexdigest() != SOURCE_SHA256:
        raise SystemExit("Use the pinned Noto Sans CJK SC Regular 2.004 font from SOURCE")
    font_info = TTFont(font_path)
    supported = font_info.getBestCmap()
    points = sorted(repertoire() & supported.keys() - {0x20, 0xFFFD})
    codepoints = [0x20, 0xFFFD] + points
    if len(codepoints) > GRID * GRID:
        raise SystemExit("Font must fit the configured atlas")
    font = ImageFont.truetype(str(font_path), 24 * SCALE)
    atlas = Image.new("L", (GRID * CELL, GRID * CELL))
    for index, point in enumerate(codepoints):
        if point == 0x20 or chr(point).isspace():
            continue
        mask = Image.new("L", (CELL * SCALE, CELL * SCALE))
        glyph = chr(0x25A1 if point == 0xFFFD else point)
        glyph_font = font
        size = 24 * SCALE
        while True:
            left, top, right, bottom = glyph_font.getbbox(glyph, anchor="ms")
            if min(left + CELL * SCALE // 2, top + 25 * SCALE) >= SCALE and max(right + CELL * SCALE // 2, bottom + 25 * SCALE) <= (CELL - 1) * SCALE:
                break
            size -= 1
            glyph_font = ImageFont.truetype(str(font_path), size)
        ImageDraw.Draw(mask).text((CELL * SCALE // 2, 25 * SCALE), glyph, font=glyph_font, fill=255, anchor="ms")
        inside = np.asarray(mask) >= 128
        distance = distance_transform_edt(inside) - distance_transform_edt(~inside)
        # Half a high-resolution pixel locates the contour between mask samples.
        distance -= np.sign(distance) * .5
        values = np.clip(127.5 + distance * 127.5 / (SPREAD * SCALE), 0, 255).astype("uint8")
        sdf = Image.fromarray(values).resize((CELL, CELL), Image.Resampling.BOX)
        atlas.paste(sdf, (index % GRID * CELL, index // GRID * CELL))
    lookup = np.zeros((256, 256, 3), dtype="uint8")
    lookup[:, :, 1] = 1  # The replacement glyph is index one.
    lookup[:, :, 2] = 199
    mapping = {f"{point:04X}": index for index, point in enumerate(codepoints)}
    for point, index in ((int(point, 16), index) for point, index in mapping.items()):
        advance = min(1.0, (font.getlength(chr(0x25A1 if point == 0xFFFD else point)) / SCALE + 1) / CELL)
        lookup[point >> 8, point & 255] = (index >> 8, index & 255, round(advance * 255))
    for point in list(range(32)) + [127, 0xA0, 0x3000]:
        lookup[point >> 8, point & 255] = (0, 0, 199 if point == 0x3000 else 64)
        mapping[f"{point:04X}"] = 0
    output.mkdir(parents=True, exist_ok=True)
    atlas.save(output / "XrtCaptionSdf.png", optimize=True)
    Image.fromarray(lookup).save(output / "XrtCaptionMap.png", optimize=True)
    manifest = {
        "format": 1, "font": "Noto Sans CJK SC Regular", "fontVersion": "2.004",
        "source": SOURCE, "sourceSha256": hashlib.sha256(source_bytes).hexdigest(),
        "license": "OFL-1.1", "licenseFile": "OFL.txt", "atlas": "XrtCaptionSdf.png",
        "lookup": "XrtCaptionMap.png", "atlasSize": [GRID * CELL, GRID * CELL],
        "cellSize": CELL, "sdfSpread": SPREAD, "replacementSourceCodepoint": "25A1",
        "lookupChannels": {"R": "atlas index high byte", "G": "atlas index low byte", "B": "cell advance / 255"}, "glyphCount": len(codepoints),
        "gpuBytes": GRID * CELL * GRID * CELL + 256 * 256 * 4,
        "coverage": ["Latin, Greek and Cyrillic present in Noto CJK", "GB2312", "Shift_JIS", "EUC-KR"],
        "codepoints": mapping,
    }
    (output / "XrtCaptionFont.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
    print(f"{len(codepoints)} glyphs; 16 MiB R8 atlas; {sum(p.stat().st_size for p in output.glob('*.png')):,} PNG bytes")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path, help="Pinned Noto Sans CJK SC Regular OTF")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--preview", type=Path)
    parser.add_argument("--bindings", action="store_true", help="Regenerate the fixed shader byte bindings")
    args = parser.parse_args()
    if args.bindings or args.font:
        build_bindings(args.output)
    if args.font:
        build(args.font, args.output)
    elif not args.preview and not args.bindings:
        parser.error("provide --font to build or --preview to render existing assets")
    if args.preview:
        render_preview(args.output, args.preview)


if __name__ == "__main__":
    main()
